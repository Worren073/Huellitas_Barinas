interface IconProps {
  name: string;
  className?: string;
  solid?: boolean;
}

export default function Icon({ name, className = '', solid = false }: IconProps) {
  const solidKey = `${name}_solid`;
  const IconComponent = solid ? (iconMap[solidKey] || iconMap[name]) : iconMap[name];

  if (!IconComponent) {
    return null;
  }

  return <IconComponent className={className} />;
}
